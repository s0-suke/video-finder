export function init() {
  // 前回と違うバージョンで起動したら知らせる（初回は知らせない）
  let last = null;
  try { last = localStorage.getItem('appVersion'); localStorage.setItem('appVersion', VERSION); } catch {}
  if (last && last !== VERSION) setTimeout(() => toast(`バージョン ${VERSION} に更新しました（設定 > バージョン情報）`), 1200);

  registerSettingsSection({
    id: 'version',
    title: 'バージョン情報',
    render(el) {
      el.innerHTML = `
        <div class="version-now">Video Finder <b>${esc(VERSION)}</b></div>
        <details class="more"><summary>更新履歴</summary>
          ${CHANGELOG.map((c) => `
            <div class="version-entry">
              <div class="version-head"><b>${esc(c.version)}</b><span class="note">${esc(c.date)}</span></div>
              <ul>${c.items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>
            </div>`).join('')}
        </details>`;
    },
  });
}
